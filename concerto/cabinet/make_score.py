"""Regenerate the Cabinet's compact stage score from the published concerto composer.
The score, not microphone input or a spectral analyzer, runs the mechanics."""
from pathlib import Path
import sys,base64,json,struct
D=Path(__file__).resolve().parent;sys.path.insert(0,str(D.parent/'production'))
import compose
VOICES=('cl','fl','bn','hn','v1','v2','va','vc')
VEL={'ppp':40,'pp':50,'p':60,'mp':72,'mf':84,'f':97,'ff':109,'fff':117}
def make():
 data=[];total=0;w=compose.build()
 for i,m in enumerate(w['movements']):
  div=24*4*m['meter'][0]//m['meter'][1];events={};gestures=[]
  for voice in VOICES:
   ev=[];vel=74
   for b,bar in enumerate(m['bars']):
    off=0
    for e in bar['parts'][voice]:
     p=e['p'];d=e['d'];start=b*div+off;off+=d
     if e.get('dyn'):vel=VEL[e['dyn']]
     if p is None:continue
     if e.get('tie') in ('stop','continue'):
      assert ev and ev[-1][2]==p;ev[-1][1]+=d
     else:ev.append([start,d,p,vel,1 if e.get('art')=='staccato' else 2 if e.get('art')=='accent' else 0])
    assert off==div
   # Recognize the exposed sixth and two falling steps, including diatonic/transposed relatives.
   # Filter isolated accompaniment coincidences: first note must belong to a notated focal desk.
   for j in range(len(ev)-3):
    a=ev[j:j+4];t=a[0][0];b=t//div;phrase=compose.PLAN[i][b//8];ld=phrase[2].split('/');speaker=ld[(b%8)*len(ld)//8]
    p=[n[2] for n in a];h=[y-x for x,y in zip(p,p[1:])]
    if speaker!=voice or h[0] not in (8,9) or h[1] not in (-1,-2) or h[2] not in (-1,-2):continue
    if a[-1][0]-t>div*3 or any(y[0]-x[0]-x[1]>.7*div for x,y in zip(a,a[1:])):continue
    gestures.append([t,VOICES.index(voice),*[n[0]-t for n in a[1:]],a[3][1]])
   total+=len(ev);events[voice]=base64.b64encode(b''.join(struct.pack('<HHBBB',*e) for e in ev)).decode()
  data.append(dict(bars=len(m['bars']),div=div,voices=events,calls=sorted(gestures),phrases=[[p[0],p[3],p[2]] for p in compose.PLAN[i]]))
 (D/'score.js').write_text('/* Generated by make_score.py. Seven bytes per actual note onset: tick, duration, concert pitch, dynamic, articulation. */\nwindow.TideManuscript='+json.dumps(data,separators=(',',':'))+';\n')
 print('Score stages:',[m['bars'] for m in data],total,'sounding onsets;', [len(m['calls']) for m in data],'four-note calls')
if __name__=='__main__':make()
