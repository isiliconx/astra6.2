'use strict';
// Run with: node --test orchestra/model.test.cjs (no dependencies).
const {test}=require('node:test');
const A=require('node:assert/strict'), {build}=require('./model.js');
const major=[0,2,4,5,7,9,11],mod=(x,n)=>(x%n+n)%n;
const tagged=(scene,occ)=>scene.events.filter(e=>e.cellSlot!==undefined && (occ===undefined||e.cellOccurrence===occ));
const onGrid=n=>Number.isInteger(n.t*4);
const timeKey=(arr,offset)=>arr.map(n=>[n.t-offset,n.p,n.len]);

test('Convergence invariants over 32 complete, independently seeded runs',()=>{
  const seeds=[1784,1742,0,1,2,3,13,99,101,65535,2147483647,'9999999999',...Array.from({length:20},(_,i)=>10007*(i+1))];
  const concerts=new Set(),gestures=new Set();
  for(const seed of seeds){
    const run=build(seed),{stages,parts,evidence}=run, [noise,key,pulse,harmony,melody,concert]=stages;
    const cell=evidence.convergence, ids=new Set(parts.map(p=>p.id));
    A.deepEqual(stages.map(s=>s.title),['Noise','Key','Pulse','Harmony','Melody','Performance']);
    A.deepEqual(stages.map(s=>s.transformation),cell.checkpoints);
    for(const sc of stages){
      A.ok(sc.events.length>0);let t=-1;
      for(const e of sc.events){
        A.ok(ids.has(e.part)); A.ok(Number.isInteger(e.p)&&e.p>=0&&e.p<=127);
        A.ok(e.v>0&&e.v<=1&&e.t>=t&&e.t>=0&&e.d>0&&e.t+e.d<=sc.bars*4+.00001);
        if(e.len!==undefined)A.ok(e.len>0&&e.t+e.len<=sc.bars*4+.00001);t=e.t;
      }
      A.ok(tagged(sc).length>=3);
    }
    // Stage 1 changes pitch, not rhythm or instrumentation.
    A.deepEqual(noise.events.map(n=>[n.t,n.d,n.part]),key.events.map(n=>[n.t,n.d,n.part]));
    const inside=sc=>sc.events.filter(e=>major.includes(mod(e.p-sc.tonic,12))).length/sc.events.length;
    A.ok(inside(key)>.95&&inside(key)>inside(noise));
    // The pulse edit retains Key's pitch stream; attacks migrate to the grid.
    A.deepEqual(key.events.map(e=>e.p),pulse.events.map(e=>e.p));
    A.ok(key.events.filter(onGrid).length<key.events.length/5);
    A.ok(pulse.events.every(onGrid));
    const ticks=cell.ticks, slots=[0,ticks[0]/4,(ticks[0]+ticks[1])/4];
    A.equal(ticks.reduce((a,b)=>a+b),8);
    const [d0,d1,d2]=cell.degreeOffsets; A.equal(d0,0);A.equal(d2-d1,-Math.sign(d1));A.ok(Math.abs(d1)>=2&&Math.abs(d1)<=4);
    for(const sc of [pulse,harmony])for(let occ=0;occ<4;occ++){
      const attacks=tagged(sc,occ);
      A.deepEqual(attacks.map(n=>n.cellSlot),[0,1,2]);A.deepEqual(attacks.map(n=>n.t-occ*8),slots);
    }
    const chordDegrees={'I':[0,2,4],'I6':[0,2,4],'ii':[1,3,5],'IV':[3,5,0],'V':[4,6,1],'V7':[4,6,1,3],'vi':[5,0,2],'Cad64':[0,2,4]};
    for(const ev of tagged(harmony)){
      const h=harmony.chords[Math.floor(ev.t/4)],degree=major.indexOf(mod(ev.p-harmony.tonic,12));
      A.ok(chordDegrees[h].includes(degree));
    }
    // Both rehearsal and finale contain actual MIDI pitches generated by the
    // seed, not just matching labels. The bar-13 return is reharmonized.
    const literal=tagged(melody,0);A.deepEqual(literal.map(e=>e.t),slots);
    const pitches=cell.degreeOffsets.map(d=>melody.tonic+12*Math.floor((d+7)/7)+major[mod(d+7,7)]);
    A.deepEqual(literal.map(n=>n.p),pitches);A.deepEqual(literal.map(n=>n.len),ticks.map(t=>t/4));
    A.deepEqual(timeKey(tagged(concert,0),0),timeKey(literal,0));
    A.deepEqual(timeKey(tagged(concert,1),48),timeKey(literal,0));
    A.notEqual(concert.chords[0],concert.chords[12]);
    A.notDeepEqual(concert.events.filter(n=>n.lead&&n.t<32),melody.events.filter(n=>n.lead));
    A.equal(new Set(concert.events.map(n=>n.part)).size,7);
    A.deepEqual(concert.chords.slice(-2),['V7','I']);
    for(const v of Object.values(evidence.heldout))A.ok(v.observations>0&&v.fittedBits>0&&v.fittedBits<v.uniformBits);
    A.equal(evidence.novelty.tested,concert.events.filter(n=>n.lead).length-8);
    A.equal(evidence.novelty.trainingMatches,0);A.equal(evidence.novelty.validationMatches,0);
    concerts.add(JSON.stringify(concert.events));gestures.add(cell.gesture);
  }
  A.equal(concerts.size,seeds.length);A.ok(gestures.size>=8);
});

test('bit-for-bit repeatability',()=>A.deepEqual(build(1784),build(1784)));
